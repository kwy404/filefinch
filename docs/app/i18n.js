export const messages = { en, pt };

let lang = 'en';
try {
  const saved = localStorage.getItem('filefinch:lang');
  lang = saved === 'pt' || saved === 'en' ? saved : /^pt\b/i.test(navigator.language || '') ? 'pt' : 'en';
} catch {}

export const getLang = () => lang;
export const locale = () => (lang === 'pt' ? 'pt-BR' : 'en');

export function setLang(next) {
  lang = next === 'pt' ? 'pt' : 'en';
  try {
    localStorage.setItem('filefinch:lang', lang);
  } catch {}
  document.documentElement.lang = locale();
  applyI18n(document);
}

export function t(key, vars) {
  let text = messages[lang][key] ?? messages.en[key] ?? key;
  if (vars) text = text.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
  return text;
}

/** Fills data-i18n (text) and data-i18n-attr ("attr:key,attr2:key2") under root. */
export function applyI18n(root) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of el.dataset.i18nAttr.split(',')) {
      const [attr, key] = pair.split(':');
      el.setAttribute(attr.trim(), t(key.trim()));
    }
  }
}
